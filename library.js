/* =========================================================================
   زِيكولا — الملف الرئيسي للمكتبة  (library.js)
   =========================================================================
   هذا هو المكان الوحيد اللي تعدّل عليه حتى تضيف كتاب جديد.

   لإضافة كتاب:
     ١) انسخ أي ملف موجود داخل مجلد  books/  وسمِّه باسم جديد
        (مثال:  books/my-book.js)
     ٢) افتح الملف وعدّل بياناته (الاسم، الكاتب، الحلقات...)
     ٣) زيد اسم الملف هنا بالقائمة تحت  BOOK_FILES  بسطر واحد فقط.

   خلص! التطبيق راح يحمّل الكتاب تلقائيًا للمستخدمين.
   ========================================================================= */

window.ZIKOLA = window.ZIKOLA || { books: [] };

/* دالة التسجيل — كل ملف كتاب ينادي ZIKOLA.register(...) حتى يضيف نفسه */
window.ZIKOLA.register = function (book) {
  window.ZIKOLA.books.push(book);
};

/* -------------------------------------------------------------------------
   قائمة ملفات الكتب — رتّبها بالترتيب اللي تحب يظهر بيه بالمكتبة.
   ------------------------------------------------------------------------- */
window.ZIKOLA.BOOK_FILES = [
  'books/book-01.js',
  'books/book-02.js',
  // 'books/my-new-book.js',   ← أضف كتبك الجديدة هنا
];

/* -------------------------------------------------------------------------
   مُحمّل الكتب — لا تعدّله. يحمّل كل الملفات أعلاه ثم يشغّل التطبيق.
   ------------------------------------------------------------------------- */
window.ZIKOLA.load = function () {
  return new Promise(resolve => {
    const files = window.ZIKOLA.BOOK_FILES || [];
    let remaining = files.length;
    if (!remaining) return resolve(window.ZIKOLA.books);
    files.forEach(src => {
      const s = document.createElement('script');
      s.src = src;
      s.onload = s.onerror = () => { if (--remaining === 0) resolve(window.ZIKOLA.books); };
      document.head.appendChild(s);
    });
  });
};
